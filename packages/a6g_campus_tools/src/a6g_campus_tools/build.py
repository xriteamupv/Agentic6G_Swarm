# ruff: noqa: E501  (SDF/XML template lines are kept whole for readability)
"""``a6g campus build``: campus v2 + OSM extract -> Gazebo world, Nav2 prior map, 2D obstacles.

Outputs (under ``world.output_dir``):

* ``worlds/<campus_id>.sdf``: ground plane, extruded building footprints, trees, and a
  ``<spherical_coordinates>`` block from the campus datum (ENU), so NavSat reports real
  latitude/longitude;
* ``worlds/<campus_id>.markers.json``: POIs, sectors and survey routes, staging, shadows and
  recovery points in the runtime frame, drawn as a GUI-only overlay by ``campus_markers``
  (never in the world itself: rendering-based LiDARs would see them);
* ``maps/<campus_id>.pgm`` + ``.yaml``: 2D occupancy grid in ``campus_map`` (the "OSM prior
  map" standing in for the D-01 LiDAR map), footprints filled: for Nav2's costmaps;
* ``maps/<campus_id>_loc.pgm`` + ``.yaml``: the same footprints as outlines
  (``world.loc_outline_m`` thick) with unknown interiors, for AMCL. A LiDAR only sees
  facades; with filled footprints the likelihood field scores points inside a building as
  perfect hits, so AMCL drifts into buildings;
* ``sim/<campus_id>_obstacles.yaml``: the same footprints for the 2D simulator;
* ``maps/<campus_id>_keepout.pgm`` + ``.yaml`` (``patrol_zones.mode: footpaths``): a Nav2
  keepout filter mask, free only within ``corridor_m`` of a footpath (the robots walk
  nowhere else; not yet loaded by a keepout costmap filter).

Deterministic: same inputs -> byte-identical files (sorted ids, fixed number formats, no
timestamps).
"""

import json
import math
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import yaml
from a6g_common.campus import CampusV2, osm_obstacles
from a6g_common.config import load_yaml

from a6g_campus_tools.osm import load_or_fetch, load_or_fetch_paths


@dataclass
class BuildResult:
    campus_id: str
    files: list[Path]
    buildings: int
    trees: int


def f3(v: float) -> str:
    return f"{v:.3f}".replace("-0.000", "0.000")


# --------------------------------------------------------------------------- SDF


def _building_height(b: dict[str, Any], campus: CampusV2) -> float:
    if b.get("height"):
        return float(b["height"])
    if b.get("levels"):
        return float(b["levels"]) * campus.world.level_height_m
    return campus.world.default_building_height_m


def world_sdf(campus: CampusV2, osm: dict[str, Any]) -> str:
    d = campus.projection()
    w = campus.world
    corners = [
        d.xy(lat, lon)
        for lat in campus.pilot_sector.bbox_wgs84[0::2]
        for lon in campus.pilot_sector.bbox_wgs84[1::2]
    ]
    size = max(max(abs(x) for x, _ in corners), max(abs(y) for _, y in corners)) * 2 + 100
    parts = [
        '<?xml version="1.0" ?>',
        "<!-- Generated by `a6g campus build` from the campus file and the OpenStreetMap extract.",
        "     Map data © OpenStreetMap contributors, ODbL 1.0. Do not edit by hand. -->",
        '<sdf version="1.9">',
        f'  <world name="{campus.world_name}">',
        '    <physics name="4ms" type="ignored"><max_step_size>0.004</max_step_size><real_time_factor>1.0</real_time_factor></physics>',
        '    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>',
        '    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>',
        '    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>',
        '    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors"><render_engine>ogre2</render_engine></plugin>',
        '    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>',
        '    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>',
        "    <spherical_coordinates>",
        "      <surface_model>EARTH_WGS84</surface_model>",
        "      <world_frame_orientation>ENU</world_frame_orientation>",
        f"      <latitude_deg>{campus.datum.lat_deg:.7f}</latitude_deg>",
        f"      <longitude_deg>{campus.datum.lon_deg:.7f}</longitude_deg>",
        f"      <elevation>{f3(campus.datum.alt_m)}</elevation>",
        f"      <heading_deg>{f3(campus.datum.heading_deg)}</heading_deg>",
        "    </spherical_coordinates>",
        '    <light type="directional" name="sun"><cast_shadows>true</cast_shadows><pose>0 0 100 0 0 0</pose>'
        "<diffuse>0.9 0.9 0.9 1</diffuse><specular>0.2 0.2 0.2 1</specular><direction>-0.5 0.1 -0.9</direction></light>",
        '    <model name="ground_plane"><static>true</static><link name="link">',
        '      <collision name="collision"><geometry><plane><normal>0 0 1</normal>'
        f"<size>{f3(size)} {f3(size)}</size></plane></geometry></collision>",
        '      <visual name="visual"><geometry><plane><normal>0 0 1</normal>'
        f"<size>{f3(size)} {f3(size)}</size></plane></geometry>"
        "<material><ambient>0.45 0.47 0.42 1</ambient><diffuse>0.45 0.47 0.42 1</diffuse></material></visual>",
        "    </link></model>",
        '    <model name="campus_buildings"><static>true</static><link name="link">',
    ]
    for b in osm["buildings"]:
        ring = [d.xy(lat, lon) for lat, lon in b["outer"]]
        if ring[0] == ring[-1]:
            ring = ring[:-1]
        if len(ring) < 3:
            continue
        points = "".join(f"<point>{f3(x)} {f3(y)}</point>" for x, y in ring)
        geom = f"<geometry><polyline>{points}<height>{f3(_building_height(b, campus))}</height></polyline></geometry>"
        parts.append(f'      <collision name="{b["id"]}_c">{geom}</collision>')
        parts.append(
            f'      <visual name="{b["id"]}_v">{geom}'
            "<material><ambient>0.78 0.74 0.68 1</ambient><diffuse>0.78 0.74 0.68 1</diffuse></material></visual>"
        )
    parts.append("    </link></model>")
    if osm["trees"]:
        parts.append('    <model name="campus_trees"><static>true</static><link name="link">')
        for t in osm["trees"]:
            x, y = d.xy(t["lat"], t["lon"])
            pose = f"<pose>{f3(x)} {f3(y)} {f3(w.tree_height_m / 2)} 0 0 0</pose>"
            geom = f"<geometry><cylinder><radius>{f3(w.tree_radius_scaled_m)}</radius><length>{f3(w.tree_height_m)}</length></cylinder></geometry>"
            parts.append(f'      <collision name="{t["id"]}_c">{pose}{geom}</collision>')
            parts.append(
                f'      <visual name="{t["id"]}_v">{pose}{geom}'
                "<material><ambient>0.2 0.5 0.2 1</ambient><diffuse>0.2 0.5 0.2 1</diffuse></material></visual>"
            )
        parts.append("    </link></model>")
    parts += _pilot_outline(campus)
    parts += ["  </world>", "</sdf>", ""]
    return "\n".join(parts)


def _pilot_outline(campus: CampusV2) -> list[str]:
    """The pilot-area boundary painted on the ground (visual only, 0.5 m wide)."""
    d = campus.projection()
    if campus.pilot_sector.polygon_wgs84 is not None:
        ring = [d.xy(lat, lon) for lat, lon in campus.pilot_sector.polygon_wgs84]
    else:
        lat0, lon0, lat1, lon1 = campus.pilot_sector.bbox_wgs84
        ring = [d.xy(lat0, lon0), d.xy(lat0, lon1), d.xy(lat1, lon1), d.xy(lat1, lon0)]
    out = ['    <model name="pilot_area"><static>true</static><link name="link">']
    for i, (a, b) in enumerate(zip(ring, ring[1:] + ring[:1], strict=True)):
        length = math.hypot(b[0] - a[0], b[1] - a[1])
        yaw = math.atan2(b[1] - a[1], b[0] - a[0])
        mx, my = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        out.append(
            f'      <visual name="edge_{i}"><pose>{f3(mx)} {f3(my)} 0.01 0 0 {yaw:.6f}</pose>'
            f"<geometry><box><size>{f3(length + 0.5)} 0.5 0.02</size></box></geometry>"
            "<material><ambient>1 0.85 0 1</ambient><diffuse>1 0.85 0 1</diffuse></material>"
            "<cast_shadows>false</cast_shadows></visual>"
        )
    out.append("    </link></model>")
    return out


def markers_json(campus: CampusV2, base: Path) -> str:
    """Campus features for the Gazebo GUI overlay (``campus_markers``), as the 2D view shows
    them: in the runtime frame, i.e. after free-space snapping on a scaled campus."""
    from a6g_common.config import CampusConfig

    c = CampusConfig.model_validate(campus.to_enu(base_dir=base))
    data = {
        "campus_id": c.campus_id,
        "world": campus.world_name,
        "scale": c.scale,
        "staging": {"x": c.staging.x, "y": c.staging.y, "area": c.staging_area},
        "sectors": [
            {
                "id": s.sector_id,
                "name": s.name,
                "polygon": s.polygon,
                "waypoints": [[w.x, w.y] for w in s.survey_waypoints],
            }
            for s in c.sectors
        ],
        "pois": [
            {"id": p.poi_id, "name": p.name, "x": p.pose.x, "y": p.pose.y, "exposed": p.exposed}
            for p in c.pois
        ],
        "shadows": c.link_shadows,
        "recovery": [
            {
                "id": r.point_id,
                "name": r.point_id.removeprefix("lrp_").replace("_", " "),
                "x": r.pose.x,
                "y": r.pose.y,
            }
            for r in c.link_recovery_points
        ],
    }
    return json.dumps(data, indent=1, sort_keys=True) + "\n"


# --------------------------------------------------------------------------- map


def _fill(
    grid: np.ndarray, x0: float, y0: float, res: float, poly: list[tuple[float, float]]
) -> None:
    """Mark cells whose centre lies inside ``poly`` (even-odd), row 0 = lowest y."""
    h, w = grid.shape
    xs = [p[0] for p in poly]
    ys = [p[1] for p in poly]
    c0, c1 = max(0, int((min(xs) - x0) / res)), min(w, int((max(xs) - x0) / res) + 2)
    r0, r1 = max(0, int((min(ys) - y0) / res)), min(h, int((max(ys) - y0) / res) + 2)
    if c0 >= c1 or r0 >= r1:
        return
    gx, gy = np.meshgrid(x0 + (np.arange(c0, c1) + 0.5) * res, y0 + (np.arange(r0, r1) + 0.5) * res)
    inside = np.zeros(gx.shape, dtype=bool)
    n = len(poly)
    for i in range(n):
        xa, ya = poly[i]
        xb, yb = poly[(i + 1) % n]
        if ya == yb:
            continue
        cond = (ya > gy) != (yb > gy)
        inside ^= cond & (gx < xa + (gy - ya) * (xb - xa) / (yb - ya))
    grid[r0:r1, c0:c1] |= inside


UNKNOWN = 128  # trinary: (255 - 128) / 255 = 0.50, between free_thresh and occupied_thresh


def _erode(mask: np.ndarray, cells: int) -> np.ndarray:
    """Binary erosion with a 4-neighbourhood, ``cells`` times (cells outside count as free)."""
    out = mask.copy()
    for _ in range(cells):
        inner = out.copy()
        inner[1:, :] &= out[:-1, :]
        inner[:-1, :] &= out[1:, :]
        inner[:, 1:] &= out[:, :-1]
        inner[:, :-1] &= out[:, 1:]
        inner[0, :] = inner[-1, :] = False
        inner[:, 0] = inner[:, -1] = False
        out = inner
    return out


def prior_map(
    campus: CampusV2,
    obstacles: list[list[tuple[float, float]]],
    *,
    outline_m: float | None = None,
) -> tuple[bytes, str]:
    """Filled footprints, or (``outline_m``) outlines with unknown interiors."""
    d = campus.projection()
    res = campus.world.map_resolution_m
    lat0, lon0, lat1, lon1 = campus.pilot_sector.bbox_wgs84
    corners = [d.xy(lat, lon) for lat in (lat0, lat1) for lon in (lon0, lon1)]
    x0 = np.floor(min(x for x, _ in corners) / res) * res
    y0 = np.floor(min(y for _, y in corners) / res) * res
    w = int(np.ceil((max(x for x, _ in corners) - x0) / res))
    h = int(np.ceil((max(y for _, y in corners) - y0) / res))
    occupied = np.zeros((h, w), dtype=bool)
    for poly in obstacles:
        _fill(occupied, float(x0), float(y0), res, poly)
    pixels = np.where(occupied, 0, 254).astype(np.uint8)
    name, what = campus.world_name, "OSM prior map"
    if outline_m is not None:
        interior = _erode(occupied, max(1, round(outline_m / res)))
        pixels[interior] = UNKNOWN
        name, what = f"{campus.world_name}_loc", "OSM localization map (outlines)"
    pixels = pixels[::-1]  # PGM row 0 = top (max y)
    header = f"P5\n# a6g campus build: {campus.campus_id} {what}\n{w} {h}\n255\n".encode()
    meta = yaml.safe_dump(
        {
            "image": f"{name}.pgm",
            "mode": "trinary",
            "resolution": res,
            "origin": [round(float(x0), 3), round(float(y0), 3), 0.0],
            "negate": 0,
            "occupied_thresh": 0.65,
            "free_thresh": 0.25,
        },
        sort_keys=True,
    )
    return (
        header + pixels.tobytes(),
        "# Nav2 prior map in campus_map (generated; OSM © contributors, ODbL)\n" + meta,
    )


def keepout_mask(campus: CampusV2, base: Path) -> tuple[bytes, str] | None:
    """Footpaths only: free within ``patrol_zones.corridor_m`` of a walkable path, keepout
    elsewhere (Nav2 keepout filter, ``scale`` mode: black = keepout)."""
    if campus.patrol_zones.mode != "footpaths" or campus.route_graph is None:
        return None
    from a6g_common.config import CampusConfig
    from a6g_common.footpaths import WALKABLE

    c = CampusConfig.model_validate(campus.to_enu(base_dir=base))
    d = campus.projection()
    res = campus.world.map_resolution_m
    lat0, lon0, lat1, lon1 = campus.pilot_sector.bbox_wgs84
    corners = [d.xy(lat, lon) for lat in (lat0, lat1) for lon in (lon0, lon1)]
    x0 = float(np.floor(min(x for x, _ in corners) / res) * res)
    y0 = float(np.floor(min(y for _, y in corners) / res) * res)
    w = int(np.ceil((max(x for x, _ in corners) - x0) / res))
    h = int(np.ceil((max(y for _, y in corners) - y0) / res))
    free = np.zeros((h, w), dtype=bool)
    r = c.walk_corridor_m
    assert c.route_graph is not None
    for e in c.route_graph.edges:
        if e.source not in WALKABLE:
            continue
        for (ax, ay), (bx, by) in zip(e.geometry, e.geometry[1:], strict=False):
            c0 = max(0, int((min(ax, bx) - r - x0) / res))
            c1 = min(w, int((max(ax, bx) + r - x0) / res) + 2)
            r0 = max(0, int((min(ay, by) - r - y0) / res))
            r1 = min(h, int((max(ay, by) + r - y0) / res) + 2)
            if c0 >= c1 or r0 >= r1:
                continue
            gx, gy = np.meshgrid(
                x0 + (np.arange(c0, c1) + 0.5) * res, y0 + (np.arange(r0, r1) + 0.5) * res
            )
            dx, dy = bx - ax, by - ay
            den = dx * dx + dy * dy or 1e-12
            t = np.clip(((gx - ax) * dx + (gy - ay) * dy) / den, 0.0, 1.0)
            free[r0:r1, c0:c1] |= np.hypot(gx - ax - t * dx, gy - ay - t * dy) <= r
    pixels = np.where(free, 254, 0).astype(np.uint8)[::-1]
    name = f"{campus.world_name}_keepout"
    header = (
        f"P5\n# a6g campus build: {campus.campus_id} footpath keepout mask\n{w} {h}\n255\n".encode()
    )
    meta = yaml.safe_dump(
        {
            "image": f"{name}.pgm",
            "mode": "scale",
            "resolution": res,
            "origin": [round(x0, 3), round(y0, 3), 0.0],
            "negate": 0,
            "occupied_thresh": 1.0,
            "free_thresh": 0.0,
        },
        sort_keys=True,
    )
    return (
        header + pixels.tobytes(),
        "# Nav2 keepout filter mask: footpaths only (generated)\n" + meta,
    )


