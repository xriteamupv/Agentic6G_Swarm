def load_campus_v2(path: Path, scale: float | None = None) -> CampusV2:
    """The campus file, with ``scale`` (or ``$A6G_WORLD_SCALE``) overriding ``world.scale``."""
    campus = CampusV2.model_validate(load_yaml(path))
    if scale is not None:
        return campus.with_scale_override({"A6G_WORLD_SCALE": str(scale)})
    return campus.with_scale_override()


def paths_cache(campus: CampusV2, base: Path) -> Path | None:
    """Where the footways of the pilot box are cached (v3 ``route_graph``)."""
    g = campus.route_graph
    if g is None or "osm" not in g.source:
        return None
    if g.paths_cache:
        return base / g.paths_cache
    osm = base / str(campus.world.osm_cache)
    return osm.with_name(osm.stem + ".paths.json")


def route_graph_artifact(campus: CampusV2, base: Path, *, refresh: bool = False) -> bytes | None:
    """v3: fetch (once) the footways and write the outdoor route graph, the
    same graph the runtime builds from the campus file, for inspection and the Gazebo
    overlay. Deterministic: same inputs, same bytes."""
    cache = paths_cache(campus, base)
    if campus.route_graph is None:
        return None
    if cache is not None:
        load_or_fetch_paths(cache, list(campus.pilot_sector.bbox_wgs84), refresh=refresh)
    enu = campus.to_enu(base_dir=base)
    return (
        json.dumps(
            {
                "campus_id": campus.world_name,
                "frame": "campus_map",
                "notes": enu.get("route_graph_notes", []),
                **enu["route_graph"],
            },
            indent=1,
            sort_keys=True,
        )
        + "\n"
    ).encode()


def build(
    campus_path: Path,
    *,
    out_dir: Path | None = None,
    refresh: bool = False,
    scale: float | None = None,
) -> BuildResult:
    """Generate every artifact; a scaled campus (world.scale != 1) gets its own file names."""
    campus = load_campus_v2(campus_path, scale)
    base = campus_path.parent
    if not campus.world.osm_cache:
        raise ValueError("world.osm_cache must be set in the campus file")
    cache = base / campus.world.osm_cache
    osm = load_or_fetch(cache, list(campus.pilot_sector.bbox_wgs84), refresh=refresh)
    out = (out_dir or (base / campus.world.output_dir)).resolve()
    cid = campus.world_name  # file names; == campus_id at scale 1
    obstacles = osm_obstacles(campus, cache)
    files: dict[Path, bytes] = {}
    files[out / "worlds" / f"{cid}.sdf"] = world_sdf(campus, osm).encode()
    files[out / "worlds" / f"{cid}.markers.json"] = markers_json(campus, base).encode()
    pgm, map_yaml = prior_map(campus, obstacles)
    files[out / "maps" / f"{cid}.pgm"] = pgm
    files[out / "maps" / f"{cid}.yaml"] = map_yaml.encode()
    pgm, map_yaml = prior_map(campus, obstacles, outline_m=campus.world.loc_outline_m)
    files[out / "maps" / f"{cid}_loc.pgm"] = pgm
    files[out / "maps" / f"{cid}_loc.yaml"] = map_yaml.encode()
    mask = keepout_mask(campus, base)
    if mask is not None:
        files[out / "maps" / f"{cid}_keepout.pgm"] = mask[0]
        files[out / "maps" / f"{cid}_keepout.yaml"] = mask[1].encode()
    graph = route_graph_artifact(campus, base, refresh=refresh)
    if graph is not None:
        files[out / "sim" / f"{cid}_route_graph.json"] = graph
    files[out / "sim" / f"{cid}_obstacles.yaml"] = yaml.safe_dump(
        {
            "campus_id": cid,
            "frame": "campus_map",
            "obstacles": [[[x, y] for x, y in poly] for poly in obstacles],
        },
        sort_keys=True,
    ).encode()
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != data:
            path.write_bytes(data)
    return BuildResult(cid, sorted(files), len(osm["buildings"]), len(osm["trees"]))
